# Independent Guide 9.1 minute-resolution table, not generated by this code.
# https://projectpluto.com/jevent.htm (2026 table, researched 2026-10-28).
# Center/umbra approximations are intentionally tested at a planning tolerance,
# not the one-second numerical solver tolerance.
@pytest.mark.parametrize("moon,kind,begin,end,tolerance", [
    ("Io", "transit", "2026-10-28T16:50:00Z", "2026-10-28T19:07:00Z", 240),
    ("Io", "shadow_transit", "2026-10-28T15:38:00Z", "2026-10-28T17:55:00Z", 240),
    ("Europa", "eclipse", "2026-10-28T09:41:00Z", None, 240),
    ("Europa", "occultation", None, "2026-10-28T14:57:00Z", 240),
    ("Ganymede", "transit", "2026-10-28T02:17:00Z", "2026-10-28T05:56:00Z", 240),
    # Callisto eclipse egress differs by ~5 minutes: approximate center/umbra
    # geometry is not a finite-disk photometric contact. Keep this limit explicit.
    ("Callisto", "eclipse", "2026-10-30T08:49:00Z", "2026-10-30T13:42:00Z", 360),
])
def test_independent_moon_reference(moon, kind, begin, end, tolerance):
    center = parse(begin or end)
    day = center.replace(hour=0, minute=0, second=0, microsecond=0)
    times = [day-timedelta(hours=8)+timedelta(minutes=5*i) for i in range(481)]
    observer = Observer(0, 0, 0, "UTC")
    ephemeris = JovianEphemeris()
    key = moon, kind
    values = [ephemeris.at(t, observer).margins[key] for t in times]
    found = intervals(times, values, lambda t: ephemeris.at(t, observer).margins[key])
    closest = min(found, key=lambda pair:abs(((pair[0] if begin else pair[1])-center).total_seconds()))
    if begin:
        assert abs((closest[0]-parse(begin)).total_seconds()) < tolerance
    if end:
        assert abs((closest[1]-parse(end)).total_seconds()) < tolerance


def test_system_ii_independent_approximation():
    # Project Pluto publishes an independent ~1 degree CM approximation:
    # https://projectpluto.com/grs_form.htm. Formula, not copied program code.
    # This includes apparent geometry/light time; using unretarded rotation or
    # System III fails by tens to hundreds of degrees.
    when = parse("2026-10-28T08:58:00Z")
    jd = when.timestamp()/86400+2440587.5
    mean = (jd-2455636.938)*360/4332.89709*pi/180
    center = 5.55*sin(mean)
    angle = ((jd-2451870.628)*360/398.884-center)*pi/180
    correction = 11*sin(angle)+5*cos(angle)-1.25*cos(mean)-center
    expected = (181.62+870.1869147*jd+correction) % 360
    actual = JovianEphemeris().at(when, Observer(0, 0, 0, "UTC")).central_meridian_ii
    assert abs((actual-expected+180) % 360-180) < 1.5


def test_observable_transitions_and_repeated_overlap_segments(config, now, settings):
    context = DetectionContext(config.observer, now, 1, HighSky())
    batch = JupiterDetector(settings, ephemeris=FixtureMoons(now)).detect(context)
    events = batch.candidates
    assert events and len({e.id for e in events}) == len(events)
    titles = [e.title for e in events]
    assert any("eclipse disappearance" in t for t in titles)
    assert any("occultation reappearance" in t for t in titles)
    assert not any("eclipse reappearance" in t or "occultation disappearance" in t for t in titles)
    pair = [e for e in events if e.kind == "jupiter.overlap" and len(e.metadata["features"]) == 2]
    triple = [e for e in events if e.kind == "jupiter.overlap" and len(e.metadata["features"]) == 3]
    assert len(pair) == 2 and len(triple) == 1
    assert pair[0].id != pair[1].id
    assert triple[0].interest > pair[0].interest
    assert all(e.interest < 90 for e in events)  # routine conditions must matter
    for e in events:
        assert e.scope in batch.scopes and e.profile == "planetary"
        assert Candidate.from_dict(e.to_dict()) == e
        assert "not finite-moon limb contacts" in e.metadata["contact_definition"]


def test_visibility_clipping_and_weather_independent_identity(config, now, settings):
    context = DetectionContext(config.observer, now, 1, HighSky())
    ephemeris = FixtureMoons(now)
    detector = JupiterDetector(settings, ephemeris=ephemeris)
    full = detector.detect(context)
    class NarrowSky(HighSky):
        def position(self, body, when, observer):
            result = super().position(body, when, observer)
            if body == "Jupiter":
                hours = (when-ephemeris.day).total_seconds()/3600
                altitude = 70-abs(hours-3)*80
                result.update(altitude_deg=altitude, geometric_altitude_deg=altitude)
            return result
    narrow = detector.detect(replace(context, astronomy=NarrowSky()))
    assert narrow.candidates
    assert {e.id for e in narrow.candidates if e.kind != "jupiter.overlap"} <= {e.id for e in full.candidates}
    assert all(e.geometry["geometric_altitude_deg"] >= settings["minimum_altitude_deg"]-.02 for e in narrow.candidates)
    assert all(e.start <= e.peak <= e.end for e in narrow.candidates)
    assert all(e.kind not in ("jupiter.eclipse", "jupiter.occultation") for e in narrow.candidates)
    repeated = detector.detect(replace(context, now=now+timedelta(minutes=17)))
    assert {e.id for e in full.candidates} == {e.id for e in repeated.candidates}


def test_grs_overlap_expiry_and_no_scientific_bypass(config, now, settings, conditions):
    settings = {**settings, "grs_enabled": True}
    context = DetectionContext(config.observer, now, 1, HighSky())
    detector = JupiterDetector(settings, ephemeris=FixtureMoons(now, settings))
    candidates = detector.detect(context).candidates
    overlaps = [e for e in candidates if e.kind == "jupiter.overlap" and any(f["phenomenon"] == "grs" for f in e.metadata["features"])]
    assert overlaps
    for e in overlaps:
        assert e.valid_until and e.end < parse(e.valid_until)
        assert e.start <= e.peak <= e.end
    event = replace(overlaps[0], interest=100)
    assessment = planetary(event, conditions)
    expiry = parse(event.valid_until)
    assert not qualified(event, assessment, config.policy(event.kind), expiry+timedelta(seconds=1))
    expired = {**settings, "grs_reference_max_age_days": 1}
    events = JupiterDetector(expired, ephemeris=FixtureMoons(now, expired)).detect(context).candidates
    assert events and all(f["phenomenon"] != "grs" for e in events for f in e.metadata["features"])
    assert all(e.valid_until is None and e.metadata["grs_status"] == "reference expired" for e in events)


def test_quality_cloud_seeing_altitude_are_separate(config, now, settings, conditions):
    context = DetectionContext(config.observer, now, 1, HighSky())
    event = JupiterDetector(settings, ephemeris=FixtureMoons(now)).detect(context).candidates[0]
    def assess(cloud=5, seeing=5, altitude=70):
        metrics = {**conditions.metrics, "cloud_total":replace(conditions.metrics["cloud_total"], value=cloud),
                   "seeing_index":Metric(seeing, "index", .8, "ECCC fixture", "native ordinal", iso(now))}
        return planetary(replace(event, geometry={**event.geometry, "altitude_deg":altitude}),
                         replace(conditions, metrics=metrics))
    good = assess()
    assert good.quality > assess(cloud=95).quality
    assert good.quality > assess(seeing=1).quality
    assert good.quality > assess(altitude=30).quality
    assert assess(seeing=0).quality is None
    assert event.interest == 64
    stale = Metric(5, "index", .8, "ECCC fixture", "native ordinal", iso(now), status="stale")
    assessment = planetary(event, replace(conditions, metrics={**conditions.metrics, "seeing_index":stale}))
    assert not assessment.usable_for_alerts


def test_shared_weather_seeing_restart_dedup_and_ui(config, store, weather, now, settings):
    settings = {**settings, "enabled":True}
    config.values["detectors"]["jupiter"] = settings
    weather_provider = FakeProvider(weather)
    seeing_provider = SeeingProvider(now, 5)
    seeing = CanadianSeeing(store, seeing_provider, config.observer,
                            {**config.values["atmosphere"]["canadian"], "enabled":True})
    conditions = ConditionsService(store, weather_provider, config.observer, config.values["atmosphere"], seeing=seeing)
    detector = JupiterDetector(settings, ephemeris=FixtureMoons(now+timedelta(days=1)))
    detectors = [detector, PlanetaryDetector(config.values["detectors"]["planetary"])]
    adapter = RecordingAdapter()
    service = Service(config, store=store, conditions=conditions, detectors=detectors, astronomy=HighSky(),
                      sources={}, adapters=[adapter], clock=lambda:now)
    config.values["notifications"].update(minimum_quality=0, minimum_confidence=0, ready_lead_hours=168)
    try:
        service.tick(now, force=False)
        predictions = service.upcoming()
        assert {"planetary", "jupiter"} <= {p["candidate"]["detector"] for p in predictions}
        assert weather_provider.calls == 1 and seeing_provider.calls == 1
        assert len(seeing_provider.point_calls) == len(set(seeing_provider.point_calls))
        assert set(seeing.consumers) == {"planetary", "jupiter"}
        initial_calls = len(seeing_provider.point_calls)
        # Delivery is deliberately bounded to five jobs per dispatch cycle.
        for _ in range(10):
            service.dispatch(now)
        sent = len(adapter.alerts)
        assert sent > 0
        service.tick(now+timedelta(minutes=5), force=False)
        assert weather_provider.calls == 1 and len(seeing_provider.point_calls) == initial_calls
        assert len(adapter.alerts) == sent
        with TestClient(create_app(service, background=False), base_url="http://localhost") as client:
            html = client.get("/?filter=1&types=jupiter").text
            assert "Canadian seeing:" in html and "Jupiter moons / Great Red Spot" in html
            event = next(p for p in predictions if p["candidate"]["detector"] == "jupiter")
            detail = client.get("/events/"+event["candidate"]["id"])
            assert detail.status_code == 200 and "Nominal geometric interval" in detail.text
            assert "shadow's edge" in detail.text or "shadow&#39;s edge" in detail.text
            assert client.get("/api/predictions?sort=interest_desc").status_code == 200
        assert weather_provider.calls == 1 and len(seeing_provider.point_calls) == initial_calls
        mail = render_message({"id":"fixture", "stage":"ready", "prediction":event}, "fixture@example.org").get_content()
        assert "Approximate center-based planning" in mail and "Canadian seeing:" in mail
        restarted = Service(config, store=Store(store.path), conditions=conditions, detectors=detectors,
                            astronomy=HighSky(), sources={}, adapters=[adapter], clock=lambda:now)
        try:
            restarted.tick(now+timedelta(minutes=6), force=False)
            assert len(adapter.alerts) == sent
        finally:
            restarted.close()
    finally:
        service.close()


