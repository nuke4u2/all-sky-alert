class HighSky:
    version = "fixture"
    def position(self, body, when, observer):
        return {"altitude_deg": -15 if body == "Sun" else 70,
                "geometric_altitude_deg": -15 if body == "Sun" else 70,
                "azimuth_deg": 180, "diameter_arcsec": 40}


class FixtureMoons:
    version = "fixture-v1"

    def __init__(self, day, settings=None):
        self.day = day.replace(hour=0, minute=0, second=0, microsecond=0)
        self.settings = settings or JupiterDetector.defaults

    def at(self, when, observer):
        hour = (when-self.day).total_seconds()/3600
        margins = {(m, k):-1 for m in MOONS for k in ("transit", "shadow_transit", "occultation", "eclipse")}
        for key, lo, hi in (
            (("Io", "transit"), 1, 5),
            (("Europa", "shadow_transit"), 2, 4),
            (("Ganymede", "transit"), 2.5, 3.5),
            (("Europa", "eclipse"), 6, 8),
            (("Europa", "occultation"), 7, 10),
        ):
            margins[key] = min(hour-lo, hi-hour)
        reference = parse(self.settings["grs_reference_utc"])
        longitude = self.settings["grs_longitude_deg"]+self.settings["grs_drift_deg_per_month"]*(when-reference).total_seconds()/86400/30.4375
        cm = (longitude+(hour-3)*870.270/24) % 360
        return JovianState(margins, cm)


